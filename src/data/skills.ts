/** Sort rule for every language section: most-used first, then everything else A-Z. */
export function sortSkills<T extends { name: string; usage: string; percent?: number }>(skills: T[]): T[] {
  const frequent = skills
    .filter((s) => s.usage === "frequent")
    .sort((a, b) => (b.percent ?? 0) - (a.percent ?? 0) || a.name.localeCompare(b.name));
  const rest = skills
    .filter((s) => s.usage !== "frequent")
    .sort((a, b) => a.name.localeCompare(b.name));
  return [...frequent, ...rest];
}
